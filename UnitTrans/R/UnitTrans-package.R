#' UnitTrans: distributions on (0,1) via transformations of baseline laws
#'
#' Given a baseline random variable \eqn{Y} with any `d/p/q` functions and a
#' strictly monotone transformation \eqn{V = g(Y)} into (0,1), the package
#' derives the density, distribution and quantile functions of \eqn{V},
#' simulates from it, fits it by maximum likelihood, ranks many candidate
#' models, tests goodness of fit and runs simulation studies.
#'
#' The density of \eqn{V} is
#' \deqn{f_V(v) = f_Y\{g^{-1}(v)\} \, |d g^{-1}(v) / dv|, \qquad 0 < v < 1.}
#' Six transformations are built in (see [trans_list()]): `"rational"`,
#' `"exponential"`, `"logit"`, `"tanh"`, `"probit"` and `"cloglog"`.
#' Baselines are referred to by name (e.g. `"gamma"` uses [stats::dgamma()],
#' [stats::pgamma()] and [stats::qgamma()]); functions are looked up on the
#' search path, then in \pkg{extraDistr} (if installed), then in \pkg{stats},
#' so user-written baselines work too.
#'
#' @section Main functions:
#' * Transformations: [trans_list()], [get_transformation()],
#'   [forward_transformation()], [inverse_transformation()].
#' * Baselines and compatibility: [baseline_params()], [check_domain()],
#'   [detect_transformations()].
#' * Distribution functions: [dtrans()], [ptrans()], [qtrans()], [rtrans()],
#'   [survival_trans()], [hazard_trans()].
#' * Moments: [moments_trans()], [summary_trans()].
#' * Estimation and inference: [fit_trans()], [loglik_trans()],
#'   [confint.transfit()], [residuals.transfit()], [predict.transfit()],
#'   [plot.transfit()].
#' * Model selection and checking: [fit_all()], [best_model()], [gof_trans()].
#' * Simulation: [simulation_study()].
#'
#' Start with the vignette: `vignette("UnitTrans")`.
#'
#' @references
#' Johnson, N. L. (1949). Systems of frequency curves generated by methods of
#' translation. *Biometrika*, 36(1/2), 149--176. \doi{10.2307/2332539}
#'
#' @importFrom stats coef vcov logLik confint nobs residuals predict
#' @keywords internal
