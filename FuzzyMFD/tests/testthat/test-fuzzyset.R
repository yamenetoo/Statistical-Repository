test_that("constructors and membership", {
  H <- fs_triangular(4.5, 6, 7.5)
  expect_equal(membership(H, c(4, 4.5, 5.25, 6, 7.5, 8)), c(0, 0, 0.5, 1, 0, 0))
  A <- fs_rectangular(5, 7)
  expect_equal(membership(A, c(4.99, 5, 6, 7, 7.01)), c(0, 1, 1, 1, 0))
  Tz <- fs_trapezoidal(0, 2, 6, 8, height = 0.5)
  expect_equal(membership(Tz, c(1, 4, 7)), c(0.25, 0.5, 0.25))
  S <- fs_singleton(3)
  expect_equal(membership(S, c(2, 3)), c(0, 1))
  expect_error(fuzzy_set(c(1, 1), c(0, 1)))
  expect_error(fuzzy_set(1:2, c(0, 2)))
  expect_equal(mf_triangular(c(0, 10, 20, 30, 40), 0, 20, 40), c(0, 0.5, 1, 0.5, 0))
  expect_equal(mf_trapezoidal(c(5, 15, 30, 50), 10, 20, 40, 60), c(0, 0.5, 1, 0.5))
  expect_equal(mf_indicator(c(4.99, 6), 5, 7), c(0, 1))
  G <- fuzzy_set_fun(function(z) mf_gaussian(z, 0, 1), -4, 4, n = 801)
  expect_equal(membership(G, 0), 1)
})

test_that("features of the membership function", {
  Tz <- fs_trapezoidal(1, 3, 5, 8)
  expect_equal(unname(fuzzy_core(Tz)[1, ]), c(3, 5))
  expect_equal(unname(fuzzy_support(Tz)[1, ]), c(1, 8))
  b <- fuzzy_boundary(Tz)
  expect_equal(nrow(b), 2L)
  expect_equal(unname(b[, 1]), c(1, 5))
  expect_equal(unname(b[, 2]), c(3, 8))
  expect_equal(crossover_points(Tz), c(2, 6.5))
  expect_true(is_normal(Tz))
  expect_true(is_fuzzy_number(Tz))
  expect_true(is.na(fuzzy_prototype(Tz)))
  expect_equal(fuzzy_prototype(fs_triangular(0, 1, 2)), 1)
  S <- fs_triangular(0, 1, 2, height = 0.6)
  expect_equal(fuzzy_height(S), 0.6)
  expect_true(is_subnormal(S))
  B <- fuzzy_set(c(0, 2, 3, 4, 6), c(0, 1, 0.7, 0.9, 0))
  expect_false(is_convex(B))
  expect_true(is_convex(fuzzy_set(c(0, 2, 3, 4, 6), c(0, 1, 1, 0.9, 0))))
})

test_that("union and intersection are exact", {
  out <- ross2000_sets("output")
  C <- fuzzy_union(out)
  expect_equal(membership(C, c(1, 4, 7, 8, 9)), c(0.25, 0.5, 0.5, 1, 0.5))
  I <- fuzzy_intersection(out$C1, out$C2)
  expect_equal(fuzzy_height(I), 1 / 3)
  expect_equal(membership(I, 20 / 3), 1 / 3)
  ## intersection of convex sets is convex
  expect_true(is_convex(fuzzy_intersection(fs_triangular(0, 2, 5),
                                           fs_trapezoidal(2, 4, 6, 8))))
  ## jumps of crisp sets are kept
  U <- fuzzy_union(fs_rectangular(5, 7), fs_triangular(6, 8, 10))
  expect_equal(membership(U, c(4.9, 5, 7.5, 9)), c(0, 1, 0.75, 0.5))
  Cc <- fuzzy_complement(fs_triangular(0, 1, 2), universe = c(0, 2))
  expect_equal(membership(Cc, c(0, 0.5, 1)), c(1, 0.5, 0))
})

test_that("fuzzification and agreement", {
  R <- fuzzify(10, spread = 0.01, relative = TRUE)
  expect_equal(unname(fuzzy_support(R)[1, ]), c(9.9, 10.1))
  low <- fs_triangular(0, 3, 7)
  expect_equal(agreement(low, 5.8), 0.3)
  a <- agreement(fs_triangular(0, 2, 4), fs_triangular(3, 5, 7))
  expect_equal(a, 0.25)
  expect_length(fuzzify(c(1, 2), 0.5), 2)
})
